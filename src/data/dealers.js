/** Normalize block string for comparison */
function normalizeKey(str) {
  if (!str) return '';
  return str
    .toUpperCase()
    .replace(/\s+/g, '')
    .replace(/-+/g, '')
    .replace(/III/g, '3')
    .replace(/II/g, '2')
    .replace(/I/g, '1');
}

/** Find block object by name */
export function getBlockData(blockName) {
  if (!blockName) return null;
  const key = normalizeKey(blockName);
  return MALDA_BLOCKS_DATA.find((b) => {
    if (normalizeKey(b.name) === key) return true;
    return b.altNames && b.altNames.some((alt) => normalizeKey(alt) === key);
  }) || null;
}

/** Get list of Gram Panchayats for a block */
export function getGramPanchayatsForBlock(blockName) {
  const block = getBlockData(blockName);
  return block ? block.gps : [];
}

/** Get dealers for a block */
export function getDealersForBlock(blockName) {
  if (!blockName) return [];
  const key = normalizeKey(blockName);
  return BLOCK_DEALERS.filter((d) => normalizeKey(d.block) === key);
}
